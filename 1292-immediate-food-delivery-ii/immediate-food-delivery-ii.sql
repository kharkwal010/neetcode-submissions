WITH CTE AS(
    SELECT *,
    ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY ORDER_DATE) AS RN
    FROM DELIVERY 
)
SELECT ROUND(((SELECT COUNT(*) FROM CTE WHERE RN = 1 AND ORDER_DATE = CUSTOMER_PREF_DELIVERY_DATE)/ COUNT(DISTINCT CUSTOMER_ID) * 100), 2)
AS IMMEDIATE_PERCENTAGE
FROM DELIVERY