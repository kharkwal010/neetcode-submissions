WITH CTE AS(
    SELECT VISITED_ON, 
    (SELECT SUM(AMOUNT) FROM CUSTOMER WHERE VISITED_ON BETWEEN
    DATE_SUB(C.VISITED_ON, INTERVAL 6 DAY) AND C.VISITED_ON) AS AMOUNT
    FROM CUSTOMER C WHERE C.VISITED_ON >= (
        SELECT DATE_ADD(MIN(VISITED_ON), INTERVAL 6 DAY) FROM CUSTOMER
    ) GROUP BY C.VISITED_ON
)
SELECT *, ROUND(AMOUNT/7, 2) AS AVERAGE_AMOUNT 
FROM CTE 




