SELECT T1.MACHINE_ID, ROUND(AVG(T2.TIMESTAMP - T1.TIMESTAMP), 3) AS PROCESSING_TIME
FROM ACTIVITY T1, ACTIVITY T2 WHERE
T2.MACHINE_ID = T1.MACHINE_ID AND
T2.PROCESS_ID = T1.PROCESS_ID AND
T1.ACTIVITY_TYPE = 'START' AND
T2.ACTIVITY_TYPE = 'END' GROUP BY T1.MACHINE_ID
